package handlers

import (
	"encoding/json"
	"fmt"
	"net/http"
	"ychba/database"
	"ychba/users"

	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

// UserRequest - это шаблон (структура) для данных пользователя
// Когда клиент отправляет JSON, Go превращает его в эту структуру
// Теги `json:"..."` - это инструкции для Go, как связать поля JSON с полями структуры
type UserRequest struct {
	Name      string `json:"name"`       // Поле "name" из JSON попадет сюда
	Age       int    `json:"age"`        // Поле "age" из JSON попадет сюда
	WorkHours int    `json:"work_hours"` // Поле "work_hours" из JSON попадет сюда
	Post      string `json:"post"`       // Поле "post" из JSON попадет сюда
}

// AddWorkHours - это главная функция, которая обрабатывает HTTP запрос
// Она принимает три параметра:
// w (ResponseWriter) - через него мы отправляем ответ обратно клиенту
// r (Request) - через него мы получаем данные от клиента
// pool - это подключение к базе данных (пул соединений)
func AddWorkHours(w http.ResponseWriter, r *http.Request, pool *pgxpool.Pool) {

	// ============ ШАГ 1: Проверяем тип запроса ============
	// HTTP имеет разные методы: GET (получить), POST (создать), PUT (обновить), DELETE (удалить)
	// Мы хотим принимать только POST, потому что добавляем данные
	if r.Method != http.MethodPost {
		// Если пришел не POST (например GET или PUT)
		// Отправляем клиенту ошибку с кодом 405 (Method Not Allowed)
		http.Error(w, "Только POST запросы", http.StatusMethodNotAllowed)
		return // Выходим из функции, дальше код не выполняется
	}

	// ============ ШАГ 2: Читаем и парсим JSON ============
	// Создаем пустую переменную типа UserRequest
	// Сейчас все поля пустые: Name="", Age=0, WorkHours=0, Post=""
	var newUser UserRequest

	// Теперь читаем JSON из тела запроса (r.Body) и заполняем структуру
	// json.NewDecoder(r.Body) - создает "читалку" JSON из запроса
	// .Decode(&newUser) - превращает JSON текст в Go структуру
	// Символ & означает "передай адрес переменной", чтобы функция могла ее изменить
	err := json.NewDecoder(r.Body).Decode(&newUser)
	if err != nil {
		// Если JSON неправильный (например: забыли закрыть кавычку, неправильный формат)
		// Отправляем ошибку 400 (Bad Request = плохой запрос)
		http.Error(w, "Неправильный JSON", http.StatusBadRequest)
		return
	}
	// defer означает "выполни это в самом конце функции"
	// Закрываем соединение с телом запроса, чтобы освободить память
	defer r.Body.Close()

	// Проверяем возраст
	if newUser.Age < 0 || newUser.Age > 150 { //Пропущен оператор `||` (ИЛИ)
		http.Error(w, "Невалидный возраст", http.StatusBadRequest)
		return
	}

	// Проверяем имя
	if len(newUser.Name) == 0 || len(newUser.Name) > 100 { // Пропущен оператор `||` (ИЛИ)
		http.Error(w, "Имя пустое или слишком длинное", http.StatusBadRequest)
		return
	}

	// Получаем контекст запроса
	// Контекст - это специальный объект, который передается во все функции БД
	// Он нужен для отмены операций и контроля времени выполнения
	ctx := r.Context()

	// ============ ШАГ 3: Пытаемся добавить пользователя в базу ============
	// Вызываем функцию InsertRow из пакета database
	// Она попытается выполнить SQL команду INSERT INTO users (...)
	// Передаем: контекст, пул соединений, и все данные пользователя
	err = database.InsertRow(ctx, pool, newUser.Name, newUser.Age, newUser.WorkHours, newUser.Post)

	// ============ ШАГ 4: Анализируем результат ============
	// Если err != nil, значит что-то пошло не так
	if err != nil {
		// Нам нужно понять, КАКАЯ именно ошибка произошла
		// Потому что на разные ошибки мы реагируем по-разному

		// Пытаемся преобразовать обычную ошибку в PostgreSQL ошибку
		// pgErr - это детальная информация об ошибке (включая код ошибки)
		// ok - это булево значение: true если преобразование удалось, false если нет
		pgErr, ok := err.(*pgconn.PgError)

		// Проверяем специальный случай: пользователь с таким именем уже существует
		// В PostgreSQL каждая ошибка имеет код
		// Код "23505" означает "нарушение уникального ограничения" (duplicate key)
		// Это происходит, когда мы пытаемся добавить пользователя с именем, которое уже есть в БД
		userAlreadyExists := ok && pgErr.Code == "23505"

		if userAlreadyExists {
			// ===== ВЕТКА: Пользователь уже существует =====
			// Вместо того чтобы добавлять нового пользователя
			// Мы обновим рабочие часы существующего пользователя
			// UpdateRowHours выполнит SQL: UPDATE users SET workhours = workhours + новые_часы WHERE name = имя
			err = database.UpdateRowHours(ctx, pool, newUser.Name, newUser.WorkHours)
			if err != nil {
				// Если обновление тоже не удалось (очень редкий случай)
				// Отправляем ошибку 500 (Internal Server Error = внутренняя ошибка сервера)
				http.Error(w, "Не удалось обновить часы", http.StatusInternalServerError)
				return
			}

			// Обновление прошло успешно!
			// Выводим информационное сообщение в консоль сервера (для разработчика)
			fmt.Printf("Пользователь %s уже был. Часы добавлены!\n", newUser.Name)

			// Отправляем успешный ответ клиенту
			w.WriteHeader(http.StatusOK)      // Код 200 = OK (всё хорошо)
			w.Write([]byte("Часы обновлены")) // Текстовое сообщение для клиента
			return                            // Выходим из функции, работа завершена
		}

		// ===== ВЕТКА: Другая ошибка БД =====
		// Если мы дошли сюда, значит ошибка НЕ связана с дубликатом
		// Это может быть:
		// - База данных недоступна (сервер упал)
		// - Нет прав доступа
		// - Таблица не существует
		// - Синтаксическая ошибка в SQL
		// Отправляем ошибку 500 с описанием проблемы
		http.Error(w, "Ошибка БД: "+err.Error(), http.StatusInternalServerError)
		return
	}

	// ============ ШАГ 5: Читаем всех пользователей из базы ============
	// Если мы дошли до этой строки, значит:
	// - Не было ошибок
	// - Пользователь успешно добавлен в базу данных
	// Теперь мы хотим отправить клиенту обновленный список ВСЕХ пользователей
	// Вызываем функцию GetAllUsers, которая выполнит SQL: SELECT * FROM users
	allUsers, err := users.GetAllUsers(ctx, pool)
	if err != nil {
		// Если не удалось прочитать из базы (редкий случай)
		http.Error(w, "Не удалось прочитать БД", http.StatusInternalServerError)
		return
	}

	// ============ ШАГ 6: Отправляем JSON ответ клиенту ============
	// Устанавливаем HTTP заголовок, который говорит клиенту:
	// "Я отправляю тебе данные в формате JSON"
	w.Header().Set("Content-Type", "application/json")

	// Устанавливаем код ответа 201 (Created = ресурс создан)
	// Это стандартный код для успешного создания нового объекта
	w.WriteHeader(http.StatusCreated)

	// Превращаем слайс Go (массив пользователей) в JSON текст и отправляем клиенту
	// json.NewEncoder(w) - создает "писалку" JSON в ответ
	// .Encode(allUsers) - превращает []User в JSON и записывает в w (ответ клиенту)
	err = json.NewEncoder(w).Encode(allUsers)
	if err != nil {
		// Если не удалось создать JSON (очень редкая ошибка, почти невозможная)
		http.Error(w, "Ошибка создания JSON", http.StatusInternalServerError)
		return
	}

	// Всё! Функция завершена успешно
	// Клиент получит JSON массив со всеми пользователями
}
